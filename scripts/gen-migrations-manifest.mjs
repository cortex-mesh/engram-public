#!/usr/bin/env node
// Regenerates src/lib/migrations-manifest.ts — the ordered list of Prisma
// migration directory names. The running app compares it to the DB's
// `_prisma_migrations` table (GET /api/health/migrations) to report schema
// drift without shipping migration SQL to the Lambda. See ADR-032.
//
// This file is COMMITTED (not build-time generated): CI runs
// `npm ci --ignore-scripts` + `npx prisma generate`, which would bypass any
// generate hook, so a build-time-only manifest would be missing at typecheck.
// Run `npm run gen:migrations-manifest` after adding a migration; a staleness
// test (tests/lib/migrations-manifest.test.ts) fails CI if it is out of date.
import { readdirSync, writeFileSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = join(root, "prisma", "migrations");
const outFile = join(root, "src", "lib", "migrations-manifest.ts");

export function readMigrationNames(dir) {
  let entries;
  try {
    entries = readdirSync(dir);
  } catch (err) {
    if (err && err.code === "ENOENT") return [];
    throw err;
  }
  return entries
    .filter((n) => {
      try {
        return statSync(join(dir, n)).isDirectory();
      } catch {
        return false;
      }
    })
    // Prisma names migrations with a monotonic numeric prefix; a lexical sort on
    // the zero-padded prefix is the applied order.
    .sort();
}

export function renderManifest(names) {
  return (
    `// GENERATED by scripts/gen-migrations-manifest.mjs — do not edit by hand.\n` +
    `// Run \`npm run gen:migrations-manifest\` after adding a migration.\n` +
    `// The ordered Prisma migrations in this repo (ADR-032).\n` +
    `export const MIGRATIONS_MANIFEST: readonly string[] = ${JSON.stringify(
      names,
      null,
      2,
    )} as const;\n`
  );
}

// Only write when run directly (not when imported by the staleness test).
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const names = readMigrationNames(migrationsDir);
  writeFileSync(outFile, renderManifest(names));
  console.log(
    `gen-migrations-manifest: wrote ${names.length} migrations → ${outFile.replace(root + "/", "")}`,
  );
}
